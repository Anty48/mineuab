/** El nom de l'id ("deepslate_diamond_ore") en l'idioma de la web. Si no el tenim, l'id arreglat. */
export function minecraftName(id: string, locale: Locale) {
  const names = NAMES[id];
  if (names) return names[locale === "ca" ? 0 : 1];
  const text = id.replace(/^[a-z0-9_.-]+:/, "").replace(/_/g, " ");
  return text.charAt(0).toUpperCase() + text.slice(1);
}
